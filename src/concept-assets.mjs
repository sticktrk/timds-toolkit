import fs from "node:fs/promises";
import path from "node:path";
import { MAX_ARTIFACT_FILE_BYTES, MAX_ARTIFACT_FILES, MAX_ARTIFACT_TOTAL_BYTES } from "./artifact-files.mjs";
import { parse as parseHtml } from "parse5";
import * as css from "css-tree";
import { SaxesParser } from "saxes";

const extensions = new Set([".html", ".css", ".svg", ".png", ".jpg", ".jpeg", ".webp", ".woff2"]);
const forbiddenElements = new Set(["script", "noscript", "base", "iframe", "frame", "frameset", "object", "embed", "applet", "portal", "fencedframe", "form", "foreignobject", "math", "animate", "animatemotion", "animatetransform", "animatecolor", "set", "discard", "handler", "listener"]);
const urlAttributes = new Set(["src", "href", "poster", "background", "action", "formaction", "cite", "longdesc", "lowsrc", "dynsrc", "usemap", "profile", "manifest"]);
const svg = "http://www.w3.org/2000/svg";
const utf8 = new TextDecoder("utf-8", { fatal: true });
const limit = extension => [".html", ".css"].includes(extension) ? 512 * 1024 : 8 * 1024 * 1024;

// concepts.json embeds every HTML piece, so the catalog as a whole must fit
// one artifact file. Publication replaces `"base": null` with the quoted CDN
// base, so check keeps this much of the file limit free for it; publication
// refuses a base longer than that. A published catalog is therefore at most
// MAX_ARTIFACT_FILE_BYTES (12,000,000) bytes.
export const CONCEPTS_BASE_RESERVE = 2_048;
export const MAX_CONCEPTS_DOCUMENT_BYTES = MAX_ARTIFACT_FILE_BYTES - CONCEPTS_BASE_RESERVE;

// The first line of the concept directory page TimDS writes. Only a
// directory carrying it is the toolkit's: a system with no src/concepts/
// keeps whatever its own build writes at concepts/, and the machine layer
// reads those pages as guidance.
export const CONCEPTS_DIRECTORY_MARKER = "<!-- Generated by TimDS from src/concepts/ -->";

/** Whether `directory` (dist/<base>/concepts) is the section TimDS rendered. */
export async function isGeneratedConceptsDirectory(directory) {
  const index = await fs.readFile(path.join(directory, "index.html"), "utf8").catch(error => {
    if (["ENOENT", "ENOTDIR", "EISDIR"].includes(error.code)) return "";
    throw error;
  });
  return index.includes(CONCEPTS_DIRECTORY_MARKER);
}

export function checkConceptPath(file) {
  if (typeof file !== "string" || !file || file.split("/").some(part => !/^[\p{L}\p{N}_-][\p{L}\p{N} ._-]*$/u.test(part) || part.endsWith(".") || part.endsWith(" "))) {
    throw new Error("expected a relative file inside the concept folder");
  }
  if (!extensions.has(path.posix.extname(file).toLowerCase())) throw new Error(`unsupported file type ${file}`);
  return file;
}

// Resolve through the folder component by component, including directories.
// Following a link and testing only its final target loses the no-links contract.
export async function readConceptFile(directory, file, maxBytes) {
  let current = directory;
  const parts = file.split("/");
  for (const [index, part] of parts.entries()) {
    current = path.join(current, part);
    const stat = await fs.lstat(current);
    if (stat.isSymbolicLink()) throw new Error(`${file} includes a symbolic link`);
    if (index + 1 < parts.length) {
      if (!stat.isDirectory()) throw new Error(`${file} has a non-directory parent`);
    } else if (!stat.isFile() || !stat.size || stat.size > maxBytes) {
      throw new Error(`${file} must be a nonempty regular file of at most ${maxBytes} bytes`);
    }
  }
  return fs.readFile(current);
}

function cssReferences(source, references, context = "stylesheet") {
  if (!source.trim()) return;
  // Strings and url() tokens are decoded by the CSS parser. Keep function
  // names and at-rules literal so every resource-bearing construct is recognized.
  if (source.includes("\\")) css.tokenize(source, (type, start, end) => {
    if ([css.tokenTypes.Function, css.tokenTypes.AtKeyword].includes(type) && source.slice(start, end).includes("\\")) {
      throw new Error("use literal CSS function and at-rule names");
    }
  });
  const tree = css.parse(source, { context, parseCustomProperty: true, onParseError(error) { throw error; } });
  css.walk(tree, node => {
    if (node.type === "Url") references.push(node.value);
    if (node.type === "Atrule" && node.name.toLowerCase() === "import") {
      const target = node.prelude?.children.first;
      if (target?.type === "String") references.push(target.value);
      else if (target?.type !== "Url") throw new Error("expected a local stylesheet in @import");
    }
    if (node.type === "Function" && /^(?:-webkit-)?(?:image-set|image|src)$/i.test(node.name)) {
      node.children.forEach(child => {
        if (child.type === "String") references.push(child.value);
      });
      css.walk(node, child => {
        if (child.type === "Function" && /^(?:var|env|attr)$/i.test(child.name)) throw new Error("image sources must name their files directly");
      });
    }
    if (node.type === "Raw" && /url|image-set|@import|src\s*\(/i.test(node.value)) throw new Error("unrecognized CSS resource reference");
  });
}

function inspectElement(tagName, attributes, references) {
  const tag = tagName.toLowerCase();
  if (forbiddenElements.has(tag)) throw new Error(`<${tagName}> is not passive mockup content`);
  for (const { name, value, prefix } of attributes) {
    const key = name.toLowerCase();
    if (key.startsWith("on") || ["srcdoc", "ping", "http-equiv", "codebase", "archive", "attributionsrc"].includes(key) || (key === "base" && prefix === "xml")) {
      throw new Error(`attribute ${name} is not passive mockup content`);
    }
    if (key === "charset" && !/^utf-?8$/i.test(value)) throw new Error("mockups must use UTF-8");
    if (key === "srcset" || key === "imagesrcset") {
      for (const entry of value.split(",")) references.push(entry.trim().split(/\s+/)[0]);
    } else if (urlAttributes.has(key)) references.push(value);
    else if (key === "style") cssReferences(value, references, "declarationList");
    else if (key !== "class" && /url\s*\(/i.test(value)) cssReferences(value, references, "value");
  }
}

function htmlReferences(source, references) {
  const pending = [parseHtml(source)];
  while (pending.length) {
    const node = pending.pop();
    if (node.tagName) inspectElement(node.tagName, node.attrs, references);
    if (node.tagName === "style") cssReferences(node.childNodes.map(child => child.value ?? "").join(""), references);
    if (node.content) pending.push(node.content);
    if (node.childNodes) for (const child of node.childNodes) pending.push(child);
  }
}

function svgReferences(source, references) {
  const parser = new SaxesParser({ xmlns: true });
  let root = true, style = null;
  parser.on("doctype", () => { throw new Error("an SVG cannot declare a DTD"); });
  parser.on("processinginstruction", () => { throw new Error("an SVG cannot load a processing instruction"); });
  parser.on("xmldecl", declaration => {
    if (declaration.encoding && !/^utf-?8$/i.test(declaration.encoding)) throw new Error("SVG must use UTF-8");
  });
  parser.on("opentag", tag => {
    if (tag.uri !== svg || (root && tag.local !== "svg")) throw new Error("expected a static SVG document");
    root = false;
    inspectElement(tag.local, Object.values(tag.attributes).map(attribute => ({ ...attribute, name: attribute.local })), references);
    if (tag.local === "style") style = "";
  });
  parser.on("text", text => { if (style !== null) style += text; });
  parser.on("cdata", text => { if (style !== null) style += text; });
  parser.on("closetag", tag => {
    if (tag.local === "style") { cssReferences(style, references); style = null; }
  });
  parser.write(source).close();
}

function localReference(from, reference) {
  const value = reference.trim();
  if (!value || value.startsWith("#")) return null;
  if (/^[a-z][\w+.-]*:|^[\/\\]|[\u0000-\u001f\\]/i.test(value)) throw new Error(`reference outside the concept: ${reference}`);
  const pathname = decodeURIComponent(value.split(/[?#]/, 1)[0]);
  if (!pathname) return null;
  if (/[\\%?#]/.test(pathname) || pathname.startsWith("/")) throw new Error(`invalid local reference: ${reference}`);
  return checkConceptPath(path.posix.join(path.posix.dirname(from), pathname));
}

export async function readConceptAssets(directory, pieces, label) {
  const files = new Map();
  const pending = new Set(pieces.map(piece => piece.file));
  let totalBytes = 0;
  for (const file of pending) {
    try {
      const extension = path.posix.extname(file).toLowerCase();
      const bytes = await readConceptFile(directory, file, limit(extension));
      totalBytes += bytes.length;
      if (pending.size > MAX_ARTIFACT_FILES || totalBytes > MAX_ARTIFACT_TOTAL_BYTES) throw new Error("concept exceeds the artifact file or byte limit");
      const references = [];
      if (extension === ".html") htmlReferences(utf8.decode(bytes), references);
      if (extension === ".css") cssReferences(utf8.decode(bytes), references);
      if (extension === ".svg") svgReferences(utf8.decode(bytes), references);
      files.set(file, bytes);
      for (const reference of references) {
        const local = localReference(file, reference);
        if (local) pending.add(local);
      }
    } catch (caught) { throw new Error(`${label}/${file}: ${caught.message}`); }
  }
  return files;
}
